"""The tables SLOOP's DIGITAL and VOICE engines read besides COMPOSER's own -> engines/sloop_tables.h.

  tools/gen_sloop_tables.py OUT.h

COMPOSER glue (US-20): eng_digital.c reads ENV_EXP (MDEC), eng_formant.c ENV_LIN (TALK). SLOOP writes them into its
felucca_tables.h (tools/sloop_gen_tables.py, SLOOP's tools/gen_tables.py copied unchanged); COMPOSER has its own core
tables (fe_tables.h), so this runs SLOOP's generator and keeps those two arrays exactly as it writes them."""
import importlib.util
import re
import sys
import tempfile
from pathlib import Path

spec = importlib.util.spec_from_file_location("sloop_gen_tables", Path(__file__).with_name("sloop_gen_tables.py"))
sg = importlib.util.module_from_spec(spec)
spec.loader.exec_module(sg)
NAMES = ("ENV_LIN", "ENV_EXP")


def main(path):
    with tempfile.TemporaryDirectory() as d:
        full = Path(d) / "felucca_tables.h"
        sg.main(str(full))
        text = full.read_text()
    L = ["/* generated by tools/gen_sloop_tables.py from SLOOP's tools/gen_tables.py (tools/sloop_gen_tables.py) */",
         "#pragma once", "#include <stdint.h>",
         f"#if FS != {sg.FS} || CTL != {sg.CTL}",
         f'#error "sloop_tables.h is made for FS {sg.FS}, CTL {sg.CTL} (fe_tables.h)"', "#endif"]
    for name in NAMES:
        m = re.search(r"^static const \w+ " + name + r"\[\d+\] = \{\n.*?^\};$", text, re.M | re.S)
        L.append(m[0])
    Path(path).write_text("\n".join(L) + "\n")
    print(f"sloop tables: {path}")


if __name__ == "__main__":
    main(sys.argv[1])
