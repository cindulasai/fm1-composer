"""COMPOSER's small screen font (firmware/gen/felucca_font.h FONT_S) for Studio (studio/web/font.js), so Studio can
read the FM-1's footer off fm1-emu's screen (US-34: NEXT: / LIVE: <name>).   usage: python3 tools/gen_studio_font.py"""
import base64, re
from pathlib import Path

APP = Path(__file__).resolve().parents[1]
SRC, OUT = APP / "firmware/gen/felucca_font.h", APP / "studio/web/font.js"


def arrays(text, font="FONT_S"):
    def nums(name):
        m = re.search(rf"{font}_{name}\[\d+\] = \{{([^}}]*)\}}", text)
        return [int(v, 0) for v in m[1].replace("\n", " ").split(",") if v.strip()]
    h, pad, first, last = map(int, re.search(rf"felucca_font_t {font} = \{{ (\d+), (\d+), (\d+), (\d+),", text).groups())
    return {"h": h, "pad": pad, "first": first, "last": last, "adv": nums("ADV"), "bw": nums("BW"), "off": nums("OFF"),
            "data": base64.b64encode(bytes(nums("DATA"))).decode()}


def render(f):
    return ("// generated by tools/gen_studio_font.py from firmware/gen/felucca_font.h (FONT_S): do not edit\n"
            f"export const FONT_S = {{ h: {f['h']}, pad: {f['pad']}, first: {f['first']}, last: {f['last']},\n"
            f"  adv: {f['adv']},\n  bw: {f['bw']},\n  off: {f['off']},\n  data: '{f['data']}' }};\n")


if __name__ == "__main__":
    OUT.write_text(render(arrays(SRC.read_text())))
