"""FM6's tables (engines/fm6_core.c, SLOOP's msfa port) -> engines/fm6_tables.h.

  tools/gen_fm6_tables.py OUT.h

COMPOSER glue: SLOOP writes these tables with the rest of its felucca_tables.h (tools/sloop_gen_tables.py, SLOOP's
tools/gen_tables.py copied unchanged). COMPOSER has its own core tables (fe_tables.h: the same SINE, FS and CTL), so
this writes only SLOOP's fm6_tables() part, as SLOOP's generator makes it."""
import importlib.util
import sys
from pathlib import Path

spec = importlib.util.spec_from_file_location("sloop_gen_tables", Path(__file__).with_name("sloop_gen_tables.py"))
sg = importlib.util.module_from_spec(spec)
spec.loader.exec_module(sg)


def main(path):
    L = ["/* generated by tools/gen_fm6_tables.py from SLOOP's tools/gen_tables.py (tools/sloop_gen_tables.py) */",
         "#pragma once", "#include <stdint.h>",
         f"#if FS != {sg.FS} || CTL != {sg.CTL}",
         f'#error "fm6_tables.h is made for FS {sg.FS}, CTL {sg.CTL} (fe_tables.h)"', "#endif"]
    L += sg.fm6_tables()
    Path(path).write_text("\n".join(L) + "\n")
    print(f"fm6 tables: {path}")


if __name__ == "__main__":
    main(sys.argv[1])
