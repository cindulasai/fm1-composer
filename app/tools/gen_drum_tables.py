"""Write firmware/src/drum_tables.h: the one SLOOP table drum_synth.c needs that Felucca-Engines' fe_tables.h lacks
(DECAY_K). The formula is SLOOP 2.8.5's tools/gen_tables.py line for line (isod89/sloop-fm1 @ bac9c05); the
chip has no FPU, so the table is computed here.
   python3 tools/gen_drum_tables.py firmware/src/drum_tables.h"""
import math, sys

FS = 44100


def arr(name, ctype, vals, per=12):                # (SLOOP's gen_tables.py arr)
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def main(path):
    L = ["/* generated by tools/gen_drum_tables.py (SLOOP's gen_tables.py DECAY_K): do not edit */", "#pragma once",
         "#include <stdint.h>"]
    # per-sample exponential decay for drum voices: 5 ms .. 4 s to -60 dB, Q16
    dms = [5.0 * (800 ** (v / 127)) for v in range(128)]
    L += arr("DECAY_K", "uint16_t", [min(65535, int(65536 * math.exp(-6.9 / (m / 1000 * FS)))) for m in dms])
    open(path, "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
