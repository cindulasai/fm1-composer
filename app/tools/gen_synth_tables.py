#!/usr/bin/env python3
"""Write firmware/src/synth_tables.h: COMPOSER's control-rate tables (the chip has no FPU: computed here).
   python3 tools/gen_synth_tables.py firmware/src/synth_tables.h"""
import math, sys

FS, CTL = 44100, 32
BPS = FS / CTL                                    # control blocks a second


def secs(p):                                      # an envelope knob 0..127 -> seconds (1 ms .. 10 s, cubic)
    return 0.001 + 10.0 * (p / 127) ** 3


def arr(name, ctype, vals, per=8):
    rows = [", ".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f"static const {ctype} {name}[{len(vals)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def main(out):
    atk = [max(1, min(1 << 24, round((1 << 24) / (secs(p) * BPS)))) for p in range(128)]          # Q24 a block
    k = [min(65535, round(65536 * math.exp(-6.9 / (secs(p) * BPS)))) for p in range(128)]        # -60 dB in secs(p)
    vel = [round(32767 * (v / 127) ** 1.6) for v in range(128)]                                  # Q15 velocity curve
    ang = [(p / 64 if p <= 64 else 1 + (p - 64) / 63) * math.pi / 4 for p in range(128)]          # 64 = centre (MIDI)
    pan_l = [round(32767 * math.cos(a)) for a in ang]                                            # constant power
    pan_r = [round(32767 * math.sin(a)) for a in ang]
    vol = [round(32767 * (v / 127) ** 2) for v in range(128)]                                    # Q15, CC7-like
    s = "/* generated by tools/gen_synth_tables.py: do not edit */\n#ifndef SYNTH_TABLES_H\n#define SYNTH_TABLES_H\n"
    s += arr("ENV_ATK", "int32_t", atk) + arr("ENV_K", "uint16_t", k) + arr("VEL_Q15", "int16_t", vel)
    s += arr("PAN_L", "int16_t", pan_l) + arr("PAN_R", "int16_t", pan_r) + arr("VOL_Q15", "int16_t", vol)
    s += "#endif\n"
    open(out, "w").write(s)


if __name__ == "__main__":
    main(sys.argv[1])
